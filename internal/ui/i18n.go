const (
	LocaleEnglish = "en"
	LocaleKorean  = "ko"
	LocaleJapan   = "ja"
	LocaleZhHans  = "zh-Hans"
	LocaleZhHant  = "zh-Hant"
	LocaleGerman  = "de"
	LocaleHindi   = "hi"
)

// SupportedLocales lists all locales supported by the GitHub Actions extension,
// matching GVX Desktop's 7 built-in languages.
var SupportedLocales = []string{
	LocaleEnglish,
	LocaleKorean,
	LocaleJapan,
	LocaleZhHans,
	LocaleZhHant,
	LocaleGerman,
	LocaleHindi,
}

// normalizeLocale maps raw BCP-47 / POSIX locale strings (e.g. "ko-KR", "zh_TW")
// to one of SupportedLocales, falling back to English.
func normalizeLocale(raw string) string {
	s := strings.ToLower(strings.ReplaceAll(strings.TrimSpace(raw), "_", "-"))
	switch {
	case s == "" || s == "en" || strings.HasPrefix(s, "en-"):
		return LocaleEnglish
	case s == "ko" || strings.HasPrefix(s, "ko-"):
		return LocaleKorean
	case s == "ja" || strings.HasPrefix(s, "ja-"):
		return LocaleJapan
	case s == "zh-hant" || strings.HasPrefix(s, "zh-hant-") ||
		s == "zh-tw" || strings.HasPrefix(s, "zh-tw-") ||
		s == "zh-hk" || strings.HasPrefix(s, "zh-hk-") ||
		s == "zh-mo" || strings.HasPrefix(s, "zh-mo-"):
		return LocaleZhHant
	case s == "zh" || s == "zh-hans" || strings.HasPrefix(s, "zh-"):
		return LocaleZhHans
	case s == "de" || strings.HasPrefix(s, "de-"):
		return LocaleGerman
	case s == "hi" || strings.HasPrefix(s, "hi-"):
		return LocaleHindi
	default:
		return LocaleEnglish
	}
}

func tr(locale, key string, args ...any) string {
	loc := normalizeLocale(locale)
	tmpl := ""
	if cat, ok := i18nCatalogs[loc]; ok {
		tmpl = cat[key]
	}
	if tmpl == "" {
		tmpl = i18nCatalogs[LocaleEnglish][key]
	}
	if tmpl == "" {
		tmpl = key
	}
	if len(args) == 0 {
		return tmpl
	}
	return fmt.Sprintf(tmpl, args...)
}

func matchLocalizedKey(val string, keys ...string) string {
	v := strings.TrimSpace(val)
	if v == "" {
		return ""
	}
	for _, key := range keys {
		for _, loc := range SupportedLocales {
			if i18nCatalogs[loc][key] == v {
				return key
			}
		}
	}
	return ""
}

